/**
 * Iceland's 2003 geothermal point map, as a worklist -- never as records.
 *
 * Decided 2026-09-23 (docs/superpowers/specs/2026-09-23-korea-iceland-
 * coverage-findings.md, decision I1). Náttúrufræðistofnun publishes the layer
 * under CC BY 4.0, 1,037 points classed by temperature, from Helgi Torfason's
 * 2003 geothermal map. It has no names and nothing in it says anyone bathes
 * anywhere, so importing it would put a temperature class on the map as a
 * bathing place -- the mistake NCEI stage two decided against. Instead the
 * build lists the warm and hot points the atlas has nothing near, and each
 * becomes a record only when a separate source shows people bathe there.
 *
 * Every point states its own positional accuracy, `nakvaemniXY`: 500 m. A
 * point is a pointer to look near, not a pin.
 */
import crypto from 'node:crypto';
import { distanceMeters } from './geo.mjs';

export const SOURCE_TITLE = 'Jarðhiti (N500V), Náttúrufræðistofnun, after Helgi Torfason 2003, Jarðhitakort af Íslandi (NI-03016)';
export const LICENCE = 'CC BY 4.0';
export const ATTRIBUTION = '"Jarðhiti (N500V)" by Náttúrufræðistofnun is licensed under CC BY 4.0';
export const WFS_URL =
  'https://gis.lmi.is/geoserver/wfs?service=WFS&version=2.0.0&request=GetFeature' +
  '&typeNames=ni:ni_n50v_serstok_vernd_1_n500v_jardhiti_p&outputFormat=application/json&srsName=EPSG:4326';

/**
 * The classes worth looking at for a bathing place, from the layer's own
 * legend: laug 25-70 C, kolsýrulaugar carbonated springs, hver above 70 C (too
 * hot to enter as a rule, but a hot spring feeding a pool is how many Icelandic
 * pools are made). Warm seeps (volgra), steam (gufa) and heat at active
 * volcanoes are not places anyone bathes.
 */
export const LOOK_AT = ['laug', 'kolsýrulaugar', 'hver'];

/** Twice the layer's stated 500 m accuracy: a point this far from every atlas record is a gap. */
export const GAP_METERS = 1000;

export const COLUMNS = ['id', 'type', 'lat', 'lng', 'accuracyMeters'];

/** WFS GeoJSON -> rows, sorted by id so the mirror is stable across fetches. */
export function rowsFromGeoJson(geojson) {
  return geojson.features
    .map((f) => ({
      id: f.properties.objectid,
      type: f.properties.hverirNI,
      lng: f.geometry.coordinates[0],
      lat: f.geometry.coordinates[1],
      accuracyMeters: f.properties.nakvaemniXY ?? null,
    }))
    .sort((a, b) => a.id - b.id);
}

const bodyOf = (rows) => rows.map((r) => COLUMNS.map((c) => r[c] ?? '').join('\t')).join('\n') + '\n';

export const sha256 = (s) => crypto.createHash('sha256').update(s, 'utf8').digest('hex');

export function toTsv(rows, retrieved) {
  const body = bodyOf(rows);
  return [
    `# ${SOURCE_TITLE}`,
    `# source:    ${WFS_URL}`,
    `# licence:   ${LICENCE} -- attribution: ${ATTRIBUTION}`,
    `# sha256:    ${sha256(body)}  (of the rows below, so a hand edit is detectable)`,
    `# retrieved: ${retrieved}`,
    '# Generated by scripts/fetch-iceland-geothermal.mjs. Do not edit by hand.',
    COLUMNS.join('\t'),
    body,
  ].join('\n');
}

/** Parse the mirror, refusing it if the rows no longer match their hash. */
export function fromTsv(text) {
  const lines = text.split(/\r?\n/);
  const pinned = lines.find((l) => l.startsWith('# sha256:'))?.split(/\s+/)[2];
  const header = lines.findIndex((l) => l === COLUMNS.join('\t'));
  if (!pinned || header < 0) throw new Error('iceland geothermal mirror: missing hash or header');
  const body = lines.slice(header + 1).filter(Boolean).join('\n') + '\n';
  if (sha256(body) !== pinned) throw new Error('iceland geothermal mirror: rows do not match the pinned sha256');
  return lines
    .slice(header + 1)
    .filter(Boolean)
    .map((l) => {
      const [id, type, lat, lng, acc] = l.split('\t');
      return { id: Number(id), type, lat: Number(lat), lng: Number(lng), accuracyMeters: acc === '' ? null : Number(acc) };
    });
}

/**
 * Points of a class worth looking at with no atlas record within GAP_METERS.
 * `records` should be the Icelandic records; a record anywhere is harmless.
 */
export function findGaps(points, records, radius = GAP_METERS) {
  return points
    .filter((p) => LOOK_AT.includes(p.type))
    .map((p) => {
      let nearest = Infinity;
      for (const r of records) nearest = Math.min(nearest, distanceMeters(p, r.location));
      return { ...p, nearestAtlasMeters: Number.isFinite(nearest) ? Math.round(nearest) : null };
    })
    .filter((p) => p.nearestAtlasMeters === null || p.nearestAtlasMeters > radius);
}
